//! SQL that makes a replay database out of placeholders only: one console user (a high id: the image's first start already made user 1), the bearer tokens the
//! fixtures present, and the devices a heartbeat answered as known. Applied after `php artisan migrate`.
//! Limit: a heartbeat answered `{"sysinfo":1}` is taken as an unknown device (it may also have been a known
//! one without inventory); later sysinfo posts create it as they did live.

use crate::fixture::list;
use serde_json::Value;
use std::collections::BTreeSet;
use std::path::Path;

fn q(s: &str) -> String {
    format!("'{}'", s.replace('\'', "''"))
}

pub fn sql(dir: &Path) -> Result<String, String> {
    let mut tokens = BTreeSet::new();
    let mut devices = std::collections::BTreeMap::new();
    for p in list(dir).map_err(|e| e.to_string())? {
        let fx: Value = serde_json::from_slice(&std::fs::read(&p).map_err(|e| e.to_string())?).map_err(|e| e.to_string())?;
        if let Some(a) = fx["request"]["headers"]["authorization"].as_str() {
            if let Some(t) = a.strip_prefix("Bearer ") {
                tokens.insert(t.to_string());
            }
        }
        if fx["path"] == "/api/heartbeat" {
            let body = &fx["request"]["body"]["value"];
            let answer = &fx["response"]["body"]["value"];
            let unknown = answer.get("sysinfo").is_some() && answer.as_object().map_or(false, |m| m.len() == 1);
            if let (Some(id), false) = (body["id"].as_str(), unknown) {
                devices.insert(id.to_string(), body["uuid"].as_str().unwrap_or("").to_string());
            }
        }
    }
    let mut s = String::from("-- generated by `hte-console seed-sql`; placeholders only\n");
    s += "INSERT INTO users (id, username, name, email, password, is_admin, is_active, created_at, updated_at) VALUES (900001, 'user-seed0001', 'text-seed0001', 'user-seed0001@example.invalid', 'x', 1, 1, datetime('now'), datetime('now'));\n";
    for t in tokens {
        s += &format!("INSERT INTO client_tokens (user_id, token, created_at, updated_at) VALUES (900001, {}, datetime('now'), datetime('now'));\n", q(&t));
    }
    for (id, uuid) in devices {
        s += &format!(
            "INSERT INTO devices (rustdesk_id, uuid, hostname, user_id, created_at, updated_at) VALUES ({}, {}, 'host-seed0001', 900001, datetime('now'), datetime('now'));\n",
            q(&id),
            q(&uuid)
        );
    }
    Ok(s)
}
